#pragma once

#include <QString>

namespace rasklad {

// Направление задаётся вызывающим кодом явно. Ядро не определяет язык.
enum class LayoutDirection {
    // Текст набран в XKB "us" (basic), но нужен текст XKB "ru" (default).
    UsToRu,
    // Текст набран в XKB "ru" (default), но нужен текст XKB "us" (basic).
    RuToUs,
};

// Чистое детерминированное преобразование по физическим клавишам ANSI.
//
// Каждый символ, который исходная раскладка выдаёт на уровне base или Shift
// печатной клавиши ANSI, заменяется символом той же клавиши и того же уровня
// в целевой раскладке. Остальные кодовые единицы UTF-16 копируются без
// изменений: символы вне раскладки, пробелы, управляющие символы, суррогаты
// (в том числе одиночные) и combining marks. Символ раскладки, за которым
// сразу следует combining mark (Unicode General Category M*), тоже не
// меняется: такой кластер нельзя набрать одним нажатием, а замена базы
// испортила бы, например, keycap-эмодзи "#️⃣".
//
// Источник символа (AltGr, dead key/compose, ISO <LSGT>, цифровой блок,
// другая раскладка) по QString неизвестен: любой символ из таблицы, кроме
// случая с combining mark, преобразуется. Пара us basic / ru default
// фиксирована; активная keymap пользователя не учитывается.
//
// Длина результата равна длине входа. Функция не выполняет I/O, не
// логирует и не хранит текст, не использует глобальное состояние.
// Неизвестное значение direction возвращает вход без изменений.
[[nodiscard]] QString convertLayout(const QString &text, LayoutDirection direction);

} // namespace rasklad
