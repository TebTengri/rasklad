#!/usr/bin/env python3
"""INPUT-LAB-002: developer-only preflight and bounded headless Hyprland smoke check.

--check (default): inspects /usr/bin/bwrap and /usr/bin/Hyprland metadata and prints
the fixed, sanitized isolation plan as JSON. Nothing is started or written.
--smoke: runs the already installed Hyprland once under bwrap with the same plan,
waits at most TIMEOUT_S for a Wayland socket in a private runtime directory, then
stops its own process group. No fallback launch without bwrap exists.

A "ready" result only means a socket appeared. It is not evidence that the sandbox
is safe, that text-input fields are protected, or that SYS-223 is complete.
See docs/INPUT-LAB-002.md.
"""
import argparse, json, os, resource, shutil, signal, stat, subprocess, sys, tempfile, time
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BWRAP, HYPRLAND = "/usr/bin/bwrap", "/usr/bin/Hyprland"
TIMEOUT_S, GRACE_S, POLL_S = 10.0, 1.0, 0.1
SANDBOX_HOME, SANDBOX_RUNTIME, SANDBOX_CONFIG = "/home/lab", "/run/lab", "/lab/hyprland.conf"
RUNTIME_TOKEN, CONFIG_TOKEN = "<private-runtime-dir>", "<generated-config>"
EXIT_PLAN, EXIT_BLOCKED, EXIT_READY, EXIT_TIMEOUT, EXIT_EXITED, EXIT_SANDBOX_FAILED = 0, 2, 10, 11, 12, 13
EXIT_CLEANUP_FAILED = 14
LIMITS = ((resource.RLIMIT_CPU, 20), (resource.RLIMIT_AS, 1 << 30), (resource.RLIMIT_NOFILE, 256),
          (resource.RLIMIT_CORE, 0), (resource.RLIMIT_FSIZE, 16 << 20))
CONFIG_TEXT = ("# Generated by rasklad INPUT-LAB-002. Standalone: no source, exec, bind or env.\n"
               "xwayland {\n    enabled = false\n}\n")
SANDBOX_ENV = (("PATH", "/usr/bin"), ("LANG", "C.UTF-8"), ("HOME", SANDBOX_HOME),
               ("XDG_RUNTIME_DIR", SANDBOX_RUNTIME), ("XDG_CONFIG_HOME", SANDBOX_HOME + "/.config"),
               ("XDG_DATA_HOME", SANDBOX_HOME + "/.local/share"), ("XDG_CACHE_HOME", SANDBOX_HOME + "/.cache"),
               ("LIBGL_ALWAYS_SOFTWARE", "1"), ("LP_NUM_THREADS", "1"),
               ("HYPRLAND_NO_RT", "1"), ("HYPRLAND_NO_CRASHREPORTER", "1"))
LAUNCHER_ENV = {"PATH": "/usr/bin"}  # bwrap itself; the sandbox gets --clearenv + SANDBOX_ENV only


class Refused(Exception):
    pass


def plan_argv(info_fd=None):
    argv = [BWRAP, "--unshare-all", "--die-with-parent", "--new-session", "--cap-drop", "ALL", "--clearenv",
            "--ro-bind", "/usr", "/usr", "--symlink", "usr/bin", "/bin", "--symlink", "usr/bin", "/sbin",
            "--symlink", "usr/lib", "/lib", "--symlink", "usr/lib", "/lib64",
            "--ro-bind-try", "/etc/ld.so.cache", "/etc/ld.so.cache", "--ro-bind-try", "/etc/fonts", "/etc/fonts",
            "--proc", "/proc", "--dev", "/dev", "--tmpfs", "/tmp", "--tmpfs", "/run", "--tmpfs", "/home",
            "--dir", SANDBOX_HOME + "/.config", "--dir", SANDBOX_HOME + "/.local/share",
            "--dir", SANDBOX_HOME + "/.cache",
            "--bind", RUNTIME_TOKEN, SANDBOX_RUNTIME, "--ro-bind", CONFIG_TOKEN, SANDBOX_CONFIG,
            "--chdir", SANDBOX_HOME]
    for key, value in SANDBOX_ENV:
        argv += ["--setenv", key, value]
    if info_fd is not None:
        argv += ["--info-fd", str(info_fd)]
    return argv + ["--", HYPRLAND, "--config", SANDBOX_CONFIG]


def materialize(argv, runtime, config):
    return [str(runtime) if a == RUNTIME_TOKEN else str(config) if a == CONFIG_TOKEN else a for a in argv]


def inspect_executable(path, lstat=os.lstat):
    try:
        st = lstat(path)
    except FileNotFoundError:
        return "missing"
    except OSError:
        return "unreadable"
    mode = st.st_mode
    if stat.S_ISLNK(mode):
        return "symlink"
    if not stat.S_ISREG(mode):
        return "not_regular"
    if st.st_uid != 0:
        return "not_root_owned"
    if mode & 0o022:
        return "writable_by_others"
    if mode & (stat.S_ISUID | stat.S_ISGID):
        return "setid"  # setuid bwrap has different semantics; refuse rather than guess
    if not mode & 0o111:
        return "not_executable"
    return "ok"


def preflight(lstat=os.lstat, euid=os.geteuid):
    exes = {name: inspect_executable(path, lstat) for name, path in (("bwrap", BWRAP), ("Hyprland", HYPRLAND))}
    issues = [f"{name}:{state}" for name, state in exes.items() if state != "ok"]
    if euid() == 0:
        issues.append("running_as_root")
    return exes, issues


def _open_private_dir(path, private):
    """Create or open a directory without following symlinks; refuse anything else."""
    try:
        os.mkdir(path, 0o700)
    except FileExistsError:
        pass
    try:
        fd = os.open(path, os.O_RDONLY | os.O_DIRECTORY | os.O_NOFOLLOW | os.O_CLOEXEC)
    except OSError as exc:
        raise Refused(f"unsafe_directory:{Path(path).name}") from exc
    try:
        meta = os.fstat(fd)
        if meta.st_uid != os.getuid():
            raise Refused(f"foreign_directory:{Path(path).name}")
        if meta.st_mode & 0o022:
            raise Refused(f"writable_directory:{Path(path).name}")
        if private:
            os.fchmod(fd, 0o700)
    finally:
        os.close(fd)


def prepare_base(root=ROOT):
    build = Path(root) / "build"
    base = build / "nested_compositor"
    for path in (build, base):
        if path.is_symlink():  # explicit check before any mkdir; O_NOFOLLOW re-checks atomically
            raise Refused(f"symlink:{path.name}")
    _open_private_dir(build, private=False)
    _open_private_dir(base, private=True)
    return base


def write_config(base):
    path = Path(base) / "hyprland.conf"
    if path.is_symlink():
        raise Refused("symlink:hyprland.conf")
    # Never truncate an existing inode: O_NOFOLLOW alone does not stop hard links.
    flags = os.O_WRONLY | os.O_CREAT | os.O_EXCL | os.O_NOFOLLOW | os.O_NONBLOCK | os.O_CLOEXEC
    try:
        fd = os.open(path, flags, 0o600)
    except OSError as exc:
        raise Refused("unsafe_config") from exc
    try:
        if not stat.S_ISREG(os.fstat(fd).st_mode):
            raise Refused("unsafe_config")
        os.write(fd, CONFIG_TEXT.encode())
        os.fchmod(fd, 0o600)
    finally:
        os.close(fd)
    return path


def _child_limits():
    os.nice(10)
    for res, value in LIMITS:
        resource.setrlimit(res, (value, value))


def _has_exited(proc):
    """Non-reaping check: a zombie leader keeps the process-group id reserved."""
    try:
        return os.waitid(os.P_PID, proc.pid, os.WEXITED | os.WNOHANG | os.WNOWAIT) is not None
    except ChildProcessError:
        return True


def wayland_socket_present(runtime):
    try:
        with os.scandir(runtime) as entries:
            for count, entry in enumerate(entries):
                if count >= 64:
                    break
                if entry.name.startswith("wayland-") and not entry.name.endswith(".lock"):
                    if stat.S_ISSOCK(entry.stat(follow_symlinks=False).st_mode):
                        return True
    except OSError:
        pass
    return False


def wait_ready(proc, runtime, clock, sleep, exited, socket_present, timeout=TIMEOUT_S):
    deadline = clock() + timeout
    while clock() < deadline:
        if exited(proc):
            return "exited"
        if socket_present(runtime):
            return "ready"
        sleep(POLL_S)
    if exited(proc):
        return "exited"
    return "ready" if socket_present(runtime) else "timeout"


def stop_group(proc, killpg, clock, sleep, exited):
    """Signal only our own process group (pgid == bwrap pid), then reap bwrap."""
    for sig in (signal.SIGTERM, signal.SIGKILL):
        try:
            killpg(proc.pid, sig)
        except ProcessLookupError:
            pass
        deadline = clock() + GRACE_S
        while not exited(proc) and clock() < deadline:
            sleep(0.05)
    try:
        proc.wait(timeout=GRACE_S)
    except subprocess.TimeoutExpired:
        return None
    return proc.returncode


def _read_info(fd):
    os.set_blocking(fd, False)
    try:
        info = json.loads(os.read(fd, 4096))
        pid = info.get("child-pid") if isinstance(info, dict) else None
        return type(pid) is int and pid > 0
    except (OSError, ValueError):
        return False


def run_smoke(root=ROOT, popen=subprocess.Popen, clock=time.monotonic, sleep=time.sleep, killpg=os.killpg,
              exited=_has_exited, socket_present=wayland_socket_present, lstat=os.lstat, euid=os.geteuid):
    exes, issues = preflight(lstat, euid)
    report = {"mode": "smoke", "tested": False, "executables": exes, "sandboxSafetyProven": False}
    if issues:
        return dict(report, status="blocked", reasons=issues), EXIT_BLOCKED
    run_dir = None
    try:
        base = prepare_base(root)
        run_dir = Path(tempfile.mkdtemp(prefix="run-", dir=base))
        config = write_config(run_dir)
        runtime = run_dir / "runtime"
        runtime.mkdir(mode=0o700)
    except (Refused, OSError) as exc:
        if run_dir is not None:
            shutil.rmtree(run_dir, ignore_errors=True)
        reason = str(exc) if isinstance(exc, Refused) else "setup_failed"
        return dict(report, status="blocked", reasons=[reason]), EXIT_BLOCKED
    read_fd, write_fd = None, None
    proc, outcome, started, returncode = None, "launch_failed", False, None
    cleanup_complete = False
    start = clock()
    try:
        read_fd, write_fd = os.pipe()
        argv = materialize(plan_argv(write_fd), runtime, config)
        proc = popen(argv, stdin=subprocess.DEVNULL, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL,
                     env=dict(LAUNCHER_ENV), cwd="/", close_fds=True, pass_fds=(write_fd,),
                     start_new_session=True, preexec_fn=_child_limits)
        os.close(write_fd)
        write_fd = None
        outcome = wait_ready(proc, runtime, clock, sleep, exited, socket_present)
    except (OSError, subprocess.SubprocessError):
        outcome = "launch_failed"
    finally:
        if write_fd is not None:
            os.close(write_fd)
        returncode = stop_group(proc, killpg, clock, sleep, exited) if proc is not None else None
        if read_fd is not None:
            started = _read_info(read_fd)
            os.close(read_fd)
        # Keep private evidence if the kernel did not confirm process reaping.
        if proc is None or returncode is not None:
            try:
                shutil.rmtree(run_dir)
                cleanup_complete = True
            except OSError:
                pass
    if not cleanup_complete:
        report.update(tested=proc is not None, status="cleanup_failed", sandboxStarted=started,
                      exitCode=None, elapsedMs=int((clock() - start) * 1000))
        return report, EXIT_CLEANUP_FAILED
    if outcome in ("exited", "ready") and not started:
        outcome = "sandbox_failed"
    code = {"ready": EXIT_READY, "timeout": EXIT_TIMEOUT, "exited": EXIT_EXITED}.get(outcome, EXIT_SANDBOX_FAILED)
    report.update(tested=proc is not None, status=outcome, sandboxStarted=started,
                  exitCode=returncode if outcome in ("exited", "sandbox_failed") else None,
                  elapsedMs=int((clock() - start) * 1000))
    return report, code


def check_report(lstat=os.lstat, euid=os.geteuid):
    exes, issues = preflight(lstat, euid)
    report = {"mode": "check", "tested": False, "sandboxSafetyProven": False,
              "status": "blocked" if issues else "plan_only", "executables": exes, "reasons": issues,
              "argv": plan_argv(), "timeoutSeconds": TIMEOUT_S,
              "limits": {resource_name(r): v for r, v in LIMITS}, "config": CONFIG_TEXT}
    return report, EXIT_BLOCKED if issues else EXIT_PLAN


def resource_name(res):
    return next(n for n in dir(resource) if n.startswith("RLIMIT_") and getattr(resource, n) == res)


def main(args=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--check", action="store_true", help="inspect and print the plan (default)")
    mode.add_argument("--smoke", action="store_true", help="bounded sandboxed start; review first")
    ns = parser.parse_args(args)
    report, code = run_smoke() if ns.smoke else check_report()
    print(json.dumps(report, sort_keys=True))
    return code


if __name__ == "__main__":
    sys.exit(main())
